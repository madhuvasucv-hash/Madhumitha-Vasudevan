        "import numpy as np\n",
        "import pandas as pd\n",
        "from sklearn.datasets import load_iris\n",
        "from sklearn.model_selection import train_test_split\n",
        "from sklearn.preprocessing import StandardScaler\n",
        "from sklearn.metrics import accuracy_score, classification_report, confusion_matrix\n",
        "\n",
        "class Perceptron:\n",
        "    def __init__(self, learning_rate=0.01, epochs=100, random_state=42):\n",
        "        \"\"\"\n",
        "        Single-layer Binary Perceptron classifier.\n",
        "        :param learning_rate: Step size (eta) for weight updates\n",
        "        :param epochs: Maximum passes over the training dataset\n",
        "        \"\"\"\n",
        "        self.lr = learning_rate\n",
        "        self.epochs = epochs\n",
        "        self.random_state = random_state\n",
        "        self.weights = None\n",
        "        self.bias = None\n",
        "        self.errors_per_epoch = []\n",
        "\n",
        "    @staticmethod\n",
        "    def _unit_step(z):\n",
        "        \"\"\"Heaviside step activation function (returns 1 if z >= 0 else 0).\"\"\"\n",
        "        return np.where(z >= 0.0, 1, 0)\n",
        "\n",
        "    def fit(self, X, y):\n",
        "        \"\"\"Trains the Perceptron using the Perceptron Learning Rule.\"\"\"\n",
        "        np.random.seed(self.random_state)\n",
        "        n_samples, n_features = X.shape\n",
        "        self.weights = np.zeros(n_features)\n",
        "        self.bias = 0.0\n",
        "        self.errors_per_epoch = []\n",
        "\n",
        "        for _ in range(self.epochs):\n",
        "            errors = 0\n",
        "            for xi, target in zip(X, y):\n",
        "                # 1. Compute linear net input and apply step activation\n",
        "                linear_output = np.dot(xi, self.weights) + self.bias\n",
        "                y_pred = self._unit_step(linear_output)\n",
        "\n",
        "                # 2. Update weights and bias only if prediction != target\n",
        "                update = self.lr * (target - y_pred)\n",
        "                self.weights += update * xi\n",
        "                self.bias += update\n",
        "                errors += int(update != 0.0)\n",
        "\n",
        "            self.errors_per_epoch.append(errors)\n",
        "            # Early stop if linearly separable and 0 training errors reached\n",
        "            if errors == 0:\n",
        "                break\n",
        "        return self\n",
        "\n",
        "    def net_input(self, X):\n",
        "        \"\"\"Computes raw linear score z = Xw + b.\"\"\"\n",
        "        return np.dot(X, self.weights) + self.bias\n",
        "\n",
        "    def predict(self, X):\n",
        "        \"\"\"Predicts binary class labels (0 or 1).\"\"\"\n",
        "        return self._unit_step(self.net_input(X))\n",
        "\n",
        "\n",
        "class MultiClassPerceptron:\n",
        "    \"\"\"One-vs-Rest (OvR) Multi-Class Perceptron wrapper.\"\"\"\n",
        "    def __init__(self, learning_rate=0.01, epochs=100):\n",
        "        self.lr = learning_rate\n",
        "        self.epochs = epochs\n",
        "        self.classifiers = {}\n",
        "\n",
        "    def fit(self, X, y):\n",
        "        self.classes_ = np.unique(y)\n",
        "        for cls in self.classes_:\n",
        "            # Create binary target: 1 for current species, 0 for all others\n",
        "            binary_y = np.where(y == cls, 1, 0)\n",
        "            clf = Perceptron(learning_rate=self.lr, epochs=self.epochs)\n",
        "            clf.fit(X, binary_y)\n",
        "            self.classifiers[cls] = clf\n",
        "        return self\n",
        "\n",
        "    def predict(self, X):\n",
        "        # Pick the class whose Perceptron produces the highest raw activation score\n",
        "        scores = np.column_stack([\n",
        "            self.classifiers[cls].net_input(X) for cls in self.classes_\n",
        "        ])\n",
        "        return self.classes_[np.argmax(scores, axis=1)]\n",
        "\n",
        "\n",
        "# =====================================================================\n",
        "# Load & Prepare the Iris Dataset\n",
        "# =====================================================================\n",
        "iris = load_iris()\n",
        "X, y = iris.data, iris.target\n",
        "target_names = iris.target_names\n",
        "\n",
        "X_train, X_test, y_train, y_test = train_test_split(\n",
        "    X, y, test_size=0.25, random_state=42, stratify=y\n",
        ")\n",
        "\n",
        "# Standardize features for faster, more stable convergence\n",
        "scaler = StandardScaler()\n",
        "X_train_scaled = scaler.fit_transform(X_train)\n",
        "X_test_scaled = scaler.transform(X_test)\n",
        "\n",
        "\n",
        "# =====================================================================\n",
        "# PART 1: Binary Perceptron (Setosa vs. Non-Setosa — Linearly Separable)\n",
        "# =====================================================================\n",
        "print(\"=== PART 1: BINARY PERCEPTRON (SETOSA VS. NON-SETOSA) ===\")\n",
        "y_train_binary = np.where(y_train == 0, 1, 0)\n",
        "y_test_binary = np.where(y_test == 0, 1, 0)\n",
        "\n",
        "binary_perceptron = Perceptron(learning_rate=0.05, epochs=50)\n",
        "binary_perceptron.fit(X_train_scaled, y_train_binary)\n",
        "\n",
        "y_pred_binary = binary_perceptron.predict(X_test_scaled)\n",
        "print(f\"Converged in {len(binary_perceptron.errors_per_epoch)} epochs (Final Train Errors: {binary_perceptron.errors_per_epoch[-1]})\")\n",
        "print(f\"Binary Test Accuracy : {accuracy_score(y_test_binary, y_pred_binary) * 100:.2f}%\\n\")\n",
        "\n",
        "\n",
        "# =====================================================================\n",
        "# PART 2: Multi-Class Perceptron (All 3 Iris Species via One-vs-Rest)\n",
        "# =====================================================================\n",
        "print(\"=== PART 2: MULTI-CLASS PERCEPTRON (ALL 3 SPECIES) ===\")\n",
        "multi_perceptron = MultiClassPerceptron(learning_rate=0.05, epochs=200)\n",
        "multi_perceptron.fit(X_train_scaled, y_train)\n",
        "\n",
        "y_pred_multi = multi_perceptron.predict(X_test_scaled)\n",
        "accuracy = accuracy_score(y_test, y_pred_multi) * 100\n",
        "\n",
        "print(f\"Multi-Class Test Accuracy: {accuracy:.2f}%\\n\")\n",
        "print(\"Confusion Matrix:\")\n",
        "print(confusion_matrix(y_test, y_pred_multi), \"\\n\")\n",
        "\n",
        "print(\"Classification Report:\")\n",
        "print(classification_report(y_test, y_pred_multi, target_names=target_names))\n",
