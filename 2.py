        "import csv\n",
        "\n",
        "def load_data(filename):\n",
        "    \"\"\"Loads training examples from a CSV file, skipping the header.\"\"\"\n",
        "    with open(filename, 'r') as file:\n",
        "        reader = csv.reader(file)\n",
        "        header = next(reader)  # Skip column names\n",
        "        data = [row for row in reader if row]  # Ignore empty rows\n",
        "    return header, data\n",
        "\n",
        "def is_consistent(hypothesis, example):\n",
        "    \"\"\"Checks if a hypothesis covers (matches) a given instance.\"\"\"\n",
        "    for h_val, x_val in zip(hypothesis, example):\n",
        "        if h_val != '?' and h_val != x_val:\n",
        "            return False\n",
        "    return True\n",
        "\n",
        "def more_general(h1, h2):\n",
        "    \"\"\"Returns True if hypothesis h1 is more general than or equal to h2.\"\"\"\n",
        "    more_gen_parts = []\n",
        "    for x, y in zip(h1, h2):\n",
        "        mg = (x == '?') or (x != '0' and (x == y or y == '0'))\n",
        "        more_gen_parts.append(mg)\n",
        "    return all(more_gen_parts)\n",
        "\n",
        "def min_generalizations(h, x):\n",
        "    \"\"\"Minimally generalizes hypothesis h so that it covers positive example x.\"\"\"\n",
        "    h_new = list(h)\n",
        "    for i in range(len(h)):\n",
        "        if h[i] == '0':\n",
        "            h_new[i] = x[i]\n",
        "        elif h[i] != x[i]:\n",
        "            h_new[i] = '?'\n",
        "    return [tuple(h_new)]\n",
        "\n",
        "def min_specializations(h, domains, x):\n",
        "    \"\"\"Minimally specializes hypothesis h so that it does NOT cover negative example x.\"\"\"\n",
        "    results = []\n",
        "    for i in range(len(h)):\n",
        "        if h[i] == '?':\n",
        "            for val in domains[i]:\n",
        "                if val != x[i]:\n",
        "                    h_new = list(h)\n",
        "                    h_new[i] = val\n",
        "                    results.append(tuple(h_new))\n",
        "        elif h[i] != '0':\n",
        "            h_new = list(h)\n",
        "            h_new[i] = '0'\n",
        "            results.append(tuple(h_new))\n",
        "    return results\n",
        "\n",
        "def candidate_elimination(data):\n",
        "    \"\"\"Executes the Candidate-Elimination algorithm and prints boundary updates.\"\"\"\n",
        "    num_attributes = len(data[0]) - 1\n",
        "\n",
        "    # Extract all possible attribute values (domains) from the dataset\n",
        "    domains = [set() for _ in range(num_attributes)]\n",
        "    for row in data:\n",
        "        for i in range(num_attributes):\n",
        "            domains[i].add(row[i])\n",
        "\n",
        "    # Initialize S to the most specific hypothesis ('0') and G to the most general ('?')\n",
        "    S = {tuple(['0'] * num_attributes)}\n",
        "    G = {tuple(['?'] * num_attributes)}\n",
        "\n",
        "    print(f\"Initial S: {S}\")\n",
        "    print(f\"Initial G: {G}\\n\" + \"-\" * 60)\n",
        "\n",
        "    for step, row in enumerate(data, 1):\n",
        "        x, label = row[:-1], row[-1].strip().lower()\n",
        "        print(f\"Step {step} | Instance: {x} | Target: {label.upper()}\")\n",
        "\n",
        "        if label in ['yes', '1', 'true', '+']:  # Positive Example\n",
        "            # 1. Remove from G any hypothesis inconsistent with x\n",
        "            G = {g for g in G if is_consistent(g, x)}\n",
        "\n",
        "            # 2. For each hypothesis s in S not consistent with x\n",
        "            S_prev = list(S)\n",
        "            for s in S_prev:\n",
        "                if not is_consistent(s, x):\n",
        "                    S.remove(s)\n",
        "                    # Add all minimal generalizations of s consistent with x\n",
        "                    S_plus = min_generalizations(s, x)\n",
        "                    for h in S_plus:\n",
        "                        # Keep only if some member of G is more general than h\n",
        "                        if any(more_general(g, h) for g in G):\n",
        "                            S.add(h)\n",
        "\n",
        "            # 3. Remove from S any hypothesis that is more general than another in S\n",
        "            S = {s for s in S if not any(more_general(s, s2) and s != s2 for s2 in S)}\n",
        "\n",
        "        else:  # Negative Example\n",
        "            # 1. Remove from S any hypothesis inconsistent with x (i.e., covers x)\n",
        "            S = {s for s in S if not is_consistent(s, x)}\n",
        "\n",
        "            # 2. For each hypothesis g in G inconsistent with x (i.e., covers x)\n",
        "            G_prev = list(G)\n",
        "            for g in G_prev:\n",
        "                if is_consistent(g, x):\n",
        "                    G.remove(g)\n",
        "                    # Add all minimal specializations of g consistent with x\n",
        "                    G_minus = min_specializations(g, domains, x)\n",
        "                    for h in G_minus:\n",
        "                        # Keep only if h is more general than some member of S\n",
        "                        if any(more_general(h, s) for s in S):\n",
        "                            G.add(h)\n",
        "\n",
        "            # 3. Remove from G any hypothesis that is less general than another in G\n",
        "            G = {g for g in G if not any(more_general(g2, g) and g != g2 for g2 in G)}\n",
        "\n",
        "        print(f\"  S_{step}: {S}\")\n",
        "        print(f\"  G_{step}: {G}\\n\" + \"-\" * 60)\n",
        "\n",
        "    return S, G\n",
        "\n",
        "def generate_version_space(S, G, domains):\n",
        "    \"\"\"Generates all intermediate hypotheses H such that S <= H <= G.\"\"\"\n",
        "    version_space = set(S).union(set(G))\n",
        "    queue = list(S)\n",
        "\n",
        "    while queue:\n",
        "        curr = queue.pop(0)\n",
        "        for i in range(len(curr)):\n",
        "            if curr[i] != '?':\n",
        "                # Generalize one attribute to '?'\n",
        "                candidate = list(curr)\n",
        "                candidate[i] = '?'\n",
        "                candidate = tuple(candidate)\n",
        "\n",
        "                # Check if candidate is bounded above by at least one hypothesis in G\n",
        "                if any(more_general(g, candidate) for g in G):\n",
        "                    if candidate not in version_space:\n",
        "                        version_space.add(candidate)\n",
        "                        queue.append(candidate)\n",
        "    return version_space\n",
