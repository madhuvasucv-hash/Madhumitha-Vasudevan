        "import pandas as pd\n",
        "import math\n",
        "from collections import Counter\n",
        "\n",
        "# Calculate Entropy\n",
        "def entropy(data, target):\n",
        "    values = data[target].value_counts()\n",
        "    total = len(data)\n",
        "\n",
        "    ent = 0\n",
        "    for count in values:\n",
        "        p = count / total\n",
        "        ent -= p * math.log2(p)\n",
        "\n",
        "    return ent\n",
        "\n",
        "\n",
        "# Calculate Information Gain\n",
        "def information_gain(data, attribute, target):\n",
        "    total_entropy = entropy(data, target)\n",
        "    values = data[attribute].unique()\n",
        "\n",
        "    weighted_entropy = 0\n",
        "\n",
        "    for value in values:\n",
        "        subset = data[data[attribute] == value]\n",
        "        weighted_entropy += (\n",
        "            len(subset) / len(data)\n",
        "        ) * entropy(subset, target)\n",
        "\n",
        "    return total_entropy - weighted_entropy\n",
        "\n",
        "\n",
        "# ID3 Algorithm\n",
        "def id3(data, attributes, target):\n",
        "\n",
        "    # If all samples belong to one class\n",
        "    if len(data[target].unique()) == 1:\n",
        "        return data[target].iloc[0]\n",
        "\n",
        "    # If no attributes remain\n",
        "    if not attributes:\n",
        "        return data[target].mode()[0]\n",
        "\n",
        "    # Select attribute with highest information gain\n",
        "    best_attribute = max(\n",
        "        attributes,\n",
        "        key=lambda attr: information_gain(\n",
        "            data, attr, target\n",
        "        )\n",
        "    )\n",
        "\n",
        "    tree = {best_attribute: {}}\n",
        "\n",
        "    for value in data[best_attribute].unique():\n",
        "        subset = data[data[best_attribute] == value]\n",
        "\n",
        "        remaining = [\n",
        "            attr for attr in attributes\n",
        "            if attr != best_attribute\n",
        "        ]\n",
        "\n",
        "        tree[best_attribute][value] = id3(\n",
        "            subset, remaining, target\n",
        "        )\n",
        "\n",
        "    return tree\n",
        "\n",
        "\n",
        "# Display Decision Tree\n",
        "def display_tree(tree, level=0):\n",
        "    if isinstance(tree, dict):\n",
        "        for attribute, branches in tree.items():\n",
        "            print(\"  \" * level + attribute)\n",
        "\n",
        "            for value, subtree in branches.items():\n",
        "                print(\"  \" * (level + 1) + str(value) + \" ->\")\n",
        "                display_tree(subtree, level + 2)\n",
        "    else:\n",
        "        print(\"  \" * level + \"Class: \" + str(tree))\n",
        "\n",
        "\n",
        "# Classify a new sample\n",
        "def predict(tree, sample):\n",
        "    if not isinstance(tree, dict):\n",
        "        return tree\n",
        "\n",
        "    attribute = next(iter(tree))\n",
        "    value = sample.get(attribute)\n",
        "\n",
        "    if value not in tree[attribute]:\n",
        "        return \"Unknown\"\n",
        "\n",
        "    return predict(tree[attribute][value], sample)\n",
