        "import numpy as np\n",
        "from sklearn.datasets import load_iris\n",
        "from sklearn.model_selection import train_test_split\n",
        "from sklearn.preprocessing import StandardScaler, OneHotEncoder\n",
        "\n",
        "class NeuralNetwork:\n",
        "    def __init__(self, input_size, hidden_size, output_size, learning_rate=0.1, seed=42):\n",
        "        np.random.seed(seed)\n",
        "        self.lr = learning_rate\n",
        "\n",
        "        # Initialize weights (Xavier/Glorot initialization) and biases\n",
        "        self.W1 = np.random.randn(input_size, hidden_size) * np.sqrt(1.0 / input_size)\n",
        "        self.b1 = np.zeros((1, hidden_size))\n",
        "\n",
        "        self.W2 = np.random.randn(hidden_size, output_size) * np.sqrt(1.0 / hidden_size)\n",
        "        self.b2 = np.zeros((1, output_size))\n",
        "\n",
        "    @staticmethod\n",
        "    def sigmoid(z):\n",
        "        # Clip values to prevent overflow in exp\n",
        "        z = np.clip(z, -500, 500)\n",
        "        return 1.0 / (1.0 + np.exp(-z))\n",
        "\n",
        "    @staticmethod\n",
        "    def sigmoid_derivative(a):\n",
        "        # Derivative with respect to activated output 'a'\n",
        "        return a * (1.0 - a)\n",
        "\n",
        "    def forward(self, X):\n",
        "        \"\"\"Forward propagation pass.\"\"\"\n",
        "        self.Z1 = np.dot(X, self.W1) + self.b1\n",
        "        self.A1 = self.sigmoid(self.Z1)\n",
        "\n",
        "        self.Z2 = np.dot(self.A1, self.W2) + self.b2\n",
        "        self.A2 = self.sigmoid(self.Z2)\n",
        "        return self.A2\n",
        "\n",
        "    def backward(self, X, y, output):\n",
        "        \"\"\"Backpropagation pass using gradient descent.\"\"\"\n",
        "        m = X.shape[0]  # Number of samples\n",
        "\n",
        "        # Output layer error and gradient\n",
        "        error_output = output - y\n",
        "        delta_output = error_output * self.sigmoid_derivative(output)\n",
        "\n",
        "        # Hidden layer error and gradient\n",
        "        error_hidden = np.dot(delta_output, self.W2.T)\n",
        "        delta_hidden = error_hidden * self.sigmoid_derivative(self.A1)\n",
        "\n",
        "        # Compute gradients for weights and biases\n",
        "        dW2 = np.dot(self.A1.T, delta_output) / m\n",
        "        db2 = np.sum(delta_output, axis=0, keepdims=True) / m\n",
        "\n",
        "        dW1 = np.dot(X.T, delta_hidden) / m\n",
        "        db1 = np.sum(delta_hidden, axis=0, keepdims=True) / m\n",
        "\n",
        "        # Update parameters\n",
        "        self.W2 -= self.lr * dW2\n",
        "        self.b2 -= self.lr * db2\n",
        "        self.W1 -= self.lr * dW1\n",
        "        self.b1 -= self.lr * db1\n",
        "\n",
        "    def train(self, X, y, epochs=10000, print_every=2000):\n",
        "        \"\"\"Training loop over specified epochs.\"\"\"\n",
        "        for epoch in range(1, epochs + 1):\n",
        "            output = self.forward(X)\n",
        "            self.backward(X, y, output)\n",
        "\n",
        "            if print_every and epoch % print_every == 0:\n",
        "                loss = np.mean(np.square(y - output))  # Mean Squared Error\n",
        "                print(f\"Epoch {epoch:5d} | MSE Loss: {loss:.6f}\")\n",
        "\n",
        "    def predict(self, X):\n",
        "        \"\"\"Returns raw probabilities from forward pass.\"\"\"\n",
        "        return self.forward(X)\n",
        "\n",
